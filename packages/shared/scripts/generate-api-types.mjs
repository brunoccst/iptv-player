// Generates src/api/generated/schema.ts from openapi/backend-openapi.json. See DECISIONS.md#d-020.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const BANNER = '// Generated by `npm run generate:api` from openapi/backend-openapi.json. Do not edit.\n\n';

export const specPath = fileURLToPath(new URL('../openapi/backend-openapi.json', import.meta.url));
export const outputPath = fileURLToPath(new URL('../src/api/generated/schema.ts', import.meta.url));

export async function generateApiTypes() {
  const spec = JSON.parse(await readFile(specPath, 'utf8'));
  return BANNER + astToString(await openapiTS(spec, { alphabetize: true }));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(outputPath, await generateApiTypes());
  console.log(`Wrote ${outputPath}`);
}
