// Builds the name parser the TV and phone app run in the system WebView, off the JavaScript thread (issue #228,
// DECISIONS.md#d-188): packages/shared/src/direct/nameRow.ts and what it imports, as one script that defines
// `parseNames(names)`. The output is checked in (modules/tv-media/android/src/main/assets/name-parser.js) and a test
// fails when it is out of date: run `npm run build:name-parser --workspace=@iptv/tv-app` after changing the parser.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const OUTPUT = fileURLToPath(new URL('../modules/tv-media/android/src/main/assets/name-parser.js', import.meta.url));
const ENTRY = fileURLToPath(new URL('../../../packages/shared/src/direct/nameRow.ts', import.meta.url));

/** The script's text. */
export async function nameParserScript() {
  const result = await build({
    stdin: {
      contents: `import { nameRow } from ${JSON.stringify(ENTRY)};\nglobalThis.parseNames = (names) => names.map(nameRow);\n`,
      resolveDir: fileURLToPath(new URL('.', import.meta.url)),
      loader: 'ts',
    },
    bundle: true,
    format: 'iife',
    // The WebView of Android 7 TVs that were never updated is Chrome 51-ish; esbuild lowers what it can.
    target: 'es2017',
    minify: true,
    legalComments: 'none',
    write: false,
    logLevel: 'silent',
  });
  return `// Generated by apps/tv-app/scripts/build-name-parser.mjs from packages/shared/src/direct/nameRow.ts. Do not edit.\n${result.outputFiles[0].text}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, await nameParserScript());
  console.log(`wrote ${OUTPUT}`);
}
